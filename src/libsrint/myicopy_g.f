
      SUBROUTINE MYICOPY_G(I1,I2,LEN)
C
C     FORMER ICOPY REMOVED BECAUSE OF CONFLICT WITH BLAS-LIBS
C     MEH (MAINZ,2005)
C

C
C THIS ROUTINE COPIES THE FIRST LEN ELEMENTS OF INTEGER
C   VECTOR I1 INTO VECTOR I2.
C
CENDK
      use mod_iop
      REAL*4 :: I1(LEN*ISD)
      REAL*4, device :: I2(LEN*ISD)
      INTEGER I,M,LEN,MP1

COLD      DO 10 I=1,LEN
COLD       I2(I)=I1(I)
COLD10    CONTINUE
      I2 = I1
      RETURN
      END
