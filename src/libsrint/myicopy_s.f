
      SUBROUTINE MYICOPY_S(I1,I2,LEN)
C
C     FORMER ICOPY REMOVED BECAUSE OF CONFLICT WITH BLAS-LIBS
C     MEH (MAINZ,2005)
C

C
C THIS ROUTINE COPIES THE FIRST LEN ELEMENTS OF INTEGER
C   VECTOR I1 INTO VECTOR I2.
C
CEND
      REAL*4 I1(LEN),I2(LEN)
      INTEGER I,M,LEN,MP1

COLD      DO 10 I=1,LEN
COLD       I2(I)=I1(I)
COLD10    CONTINUE
      CALL SCOPY(LEN, I1, 1, I2, 1)
      RETURN
      END
